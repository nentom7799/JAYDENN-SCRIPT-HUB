create table if not exists public.scripts (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 70),
  game text not null check (char_length(game) between 1 and 50),
  access text not null check (access in ('key','no-key')),
  description text not null default '' check (char_length(description) <= 220),
  code text not null check (char_length(code) between 1 and 30000),
  created_at timestamptz not null default now()
);

create table if not exists public.site_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.scripts enable row level security;
alter table public.site_admins enable row level security;

-- An authenticated user can verify only their own allowlist row.
-- This lets the scripts write policies check admin membership without exposing the admin list.
create policy "Admins can read own allowlist row"
on public.site_admins for select
to authenticated
using (user_id = (select auth.uid()));

-- Public visitors can read resource entries only.
create policy "Public can read scripts"
on public.scripts for select
to anon, authenticated
using (true);

-- Only explicitly allowlisted authenticated users can create/update/delete.
create policy "Admins can insert scripts"
on public.scripts for insert
to authenticated
with check (exists (select 1 from public.site_admins a where a.user_id = (select auth.uid())));

create policy "Admins can update scripts"
on public.scripts for update
to authenticated
using (exists (select 1 from public.site_admins a where a.user_id = (select auth.uid())))
with check (exists (select 1 from public.site_admins a where a.user_id = (select auth.uid())));

create policy "Admins can delete scripts"
on public.scripts for delete
to authenticated
using (exists (select 1 from public.site_admins a where a.user_id = (select auth.uid())));

